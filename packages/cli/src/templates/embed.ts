export type EmbedOptions = {
  src: string;
  title: string;
  height: string;
  fullscreen: boolean;
  checkSrc: boolean;
};

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, character => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  })[character]!);
}

function page(options: EmbedOptions, plain: boolean): string {
  const title = escapeHtml(options.title);
  const src = escapeHtml(options.src);
  const content = plain
    ? `<iframe title="${title}" src="${src}"
        sandbox="allow-scripts allow-same-origin allow-pointer-lock allow-forms"
        allow="autoplay 'src'; fullscreen ${options.fullscreen ? "'src'" : "'none'"}; camera 'none'; microphone 'none'; geolocation 'none'"
        ${options.fullscreen ? 'allowfullscreen ' : ''}referrerpolicy="no-referrer"></iframe>`
    : `<urk-player id="experience" title="${title}" src="${src}"${options.fullscreen ? ' fullscreen' : ''}${options.checkSrc ? ' check-src' : ''}></urk-player>`;
  return `<!--
  Company: EonHive Inc. | Title: Generated uRK Embed Page
  Purpose: Host a trusted static export from a separate origin.
  Author: Stan Nesi | Created: 2026-10-17 | Updated: 2026-10-17
  Notes: Vibe coded with Codex. Generated by urk embed.
-->
<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>${title}</title>
    ${plain ? '' : '<script type="module" src="./urk-player.js"></script>'}
    <style>
      * { box-sizing: border-box; }
      body { margin: 0; padding: clamp(16px, 3vw, 32px); background: #f4f7fb; color: #0f172a; font: 16px/1.5 system-ui, sans-serif; }
      main { max-width: 1200px; margin: auto; }
      h1 { overflow-wrap: anywhere; }
      urk-player, iframe { width: 100%; height: ${options.height}; min-height: 260px; }
      iframe { display: block; border: 1px solid #cbd5e1; border-radius: 12px; background: white; }
      a { color: #1d4ed8; }
    </style>
  </head>
  <body>
    <main>
      <h1>${title}</h1>
      <p>Click inside to interact. Scroll inside the experience to reach its controls.</p>
      <!-- Serve this page on a DIFFERENT origin from the experience. See HOSTING.txt. -->
      ${content}
      <p><a href="./${plain ? 'index.html' : 'plain-iframe.html'}">${plain ? 'Open with Player controls' : 'Open the plain iframe version'}</a></p>
    </main>
  </body>
</html>
`;
}

export function createEmbedTemplate(options: EmbedOptions): Record<string, string> {
  return {
    'index.html': page(options, false),
    'plain-iframe.html': page(options, true),
    'HOSTING.txt': `uRK static embed

Upload this entire directory to an ordinary static HTTP(S) host.
The experience is already hosted at:
${options.src}

Keep the embed page on a DIFFERENT origin from the experience. A different
port or hostname works; a different folder alone does not. HTTPS embedding
requires an HTTPS experience. Use HTTP hosting, not file://.

Local example: python3 -m http.server 8081 --directory <this-directory>
Choose a port different from the experience's port, then open /index.html.
plain-iframe.html uses no Player module and needs the same origin separation.
Relative links and the local urk-player.js work under static hosting subpaths.

The website's visitors need only a browser. Copy the script and urk-player
element from index.html into another page if desired, adjusting the module URL.
Title, height, fullscreen, and optional check-src can be edited in the HTML.
The Player owns no application lifecycle; Play loads/focuses and Reload starts
a fresh document. Audio may need a click inside the experience.

${options.checkSrc ? 'check-src is enabled: the experience host must permit CORS HEAD requests and return an HTML Content-Type.' : 'check-src is disabled: normal iframe navigation does not require CORS.'}
Loaded means iframe navigation, not verified application health. The experience
host must allow framing (CSP frame-ancestors / X-Frame-Options).

Use trusted exports only. Do not redirect or navigate the experience onto the
parent origin. No untrusted-package containment, privileged bridge, or ZIP
mounting is provided. Unpack .urkpkg files and host their web files first.
Generation did not fetch, validate availability, or deploy the experience URL.
`,
  };
}
